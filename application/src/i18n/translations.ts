// i18n — translation dictionaries.
//
// English is the source of truth: `TranslationKey` is derived from the `en` object, and
// `translations` is typed as `Record<Locale, Record<TranslationKey, string>>`, so the type
// system enforces that every locale provides every key. Add a key to `en` and any locale that
// is missing it fails to compile.
//
// We deliberately avoid a runtime translation API (Google Translate, etc.): the app must work
// offline on a phone at a door, and a free API would add a network dependency, a key, and a
// rate limit to a core feature. Hard-coded, reviewed translations are the right trade-off here.

